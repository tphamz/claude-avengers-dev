def cmd_md_status(project_dir: Path, path: str | None) -> int:
    ws = require_workstation(project_dir, path)
    if not ws.is_dir():
        raise WSError(f"workstation not found: {ws}")
    top = git_toplevel(ws)
    _, repo_name = remote_key(project_dir)
    if top is None:
        print(json.dumps({"git": False, "path": str(ws), "count": 0, "dirty": []}, indent=2))
        return 2
    real_top = Path(os.path.realpath(top))
    rel = Path(os.path.realpath(ws)).relative_to(real_top).as_posix() or "."
    proc = run_git(real_top, "status", "--porcelain=v1", "-z", "--untracked-files=all",
                   "--", rel)
    entries = proc.stdout.split("\0") if proc and proc.returncode == 0 else []
    dirty, skip = [], False
    for entry in entries:
        if skip:
            skip = False
            continue
        if not entry:
            continue
        dirty.append(entry[3:])
        skip = entry[0] in "RC"
    real_project = Path(os.path.realpath(project_dir))
    dedicated = (real_top != Path(os.path.realpath(Path.home()))
                 and not is_within(real_project, real_top))
    print(json.dumps({"git": True, "toplevel": str(real_top), "rel": rel,
                      "dedicated": dedicated,
                      "repo_name": repo_name or project_dir.name,
                      "count": len(dirty), "dirty": dirty}, indent=2))
    return 0 if dirty else 2


def cmd_grant_path(project_dir: Path, path: str | None) -> int:
    ws = require_workstation(project_dir, path)
    print(os.path.realpath(ws))
    return 0


# --------------------------------------------------------------------------- unlink

def cmd_unlink(project_dir: Path, dry_run: bool) -> int:
    settings = project_settings(project_dir)
    kept = settings.get("mdWorkstation")
    removed = unwire(project_dir, dry_run)
    actions = list(removed["actions"])
    for field in ("mdWorkstation", "mdLinks"):
        if field in settings:
            actions.append(f"remove {field} from {PROJECT_SETTINGS.as_posix()}")
    _kept_note(removed["exclude_kept"])
    if not actions:
        print("no workstation wiring found (no-op)", file=sys.stderr)
        return 2
    if not dry_run and ("mdWorkstation" in settings or "mdLinks" in settings):
        settings.pop("mdWorkstation", None)
        settings.pop("mdLinks", None)
        save_json(project_dir / PROJECT_SETTINGS, settings)
    print(json.dumps({"actions": actions, "kept": kept if kept != IN_REPO else None,
                      "exclude_kept": removed["exclude_kept"], "dry_run": dry_run}, indent=2))
    return 0


