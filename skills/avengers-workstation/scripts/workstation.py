def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if sys.platform == "win32":
        print("ERROR: the md workstation needs directory symlinks; Windows is not supported",
              file=sys.stderr)
        return 1
    project_dir = Path(os.path.normpath(args.project_dir.expanduser().absolute()))
    if not project_dir.is_dir():
        print(f"ERROR: project directory not found: {project_dir}", file=sys.stderr)
        return 1
    try:
        if args.command == "resolve":
            print(json.dumps(resolve(project_dir, tuple(args.link)), indent=2))
            return 0
        if args.command == "set":
            return cmd_set(project_dir, args.path, args.root, args.in_repo, args.dry_run,
                           tuple(args.link))
        if args.command == "migrate":
            return cmd_migrate(project_dir, args.path, args.root, args.untrack, args.dry_run,
                               args.link)
        if args.command == "check-config":
            return cmd_check_config(project_dir)
        if args.command == "repoint-config":
            return cmd_repoint(project_dir, args.key, args.decline, args.dry_run)
        if args.command == "md-status":
            return cmd_md_status(project_dir, args.path)
        if args.command == "grant-path":
            return cmd_grant_path(project_dir, args.path)
        if args.command == "kb-rules":
            return cmd_kb_rules(project_dir, args.dry_run)
        return cmd_unlink(project_dir, args.dry_run)
    except (WSError, OSError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
